// Helper to create STCW certificates
function makeCert(name: string, no: string, expiry: string, compliant = true): import('../types').STCWCertificate {
  return {
    id: 'CERT-' + Math.random().toString(36).substr(2, 6),
    name,
    certNo: no,
    issueDate: '2022-01-15',
    expiryDate: expiry,
    issuingAuthority: '交通部航港局 (Maritime and Port Bureau)',
    isCompliant: compliant,
  };
}

